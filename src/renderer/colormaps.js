'use strict';
/**
 * colormaps.js —— 瀑布图色图
 * 每个色图是一个 256 项的查找表（LUT）：强度 0..255 → [r,g,b]。
 * 画瀑布时每个像素只查一次表，比每次算颜色快得多。
 */
(function () {
  // 在若干个"关键颜色"之间线性插值，生成 256 项的表
  function ramp(stops) {
    const lut = new Uint8Array(256 * 3);
    for (let i = 0; i < 256; i++) {
      const x = i / 255;
      let j = 0;
      while (j < stops.length - 2 && x > stops[j + 1][0]) j++;
      const [x0, c0] = stops[j];
      const [x1, c1] = stops[j + 1];
      const t = Math.min(1, Math.max(0, (x - x0) / (x1 - x0)));
      for (let k = 0; k < 3; k++) lut[i * 3 + k] = Math.round(c0[k] + (c1[k] - c0[k]) * t);
    }
    return lut;
  }
  window.COLORMAPS = {
    // 接近 SDR# 默认：黑 → 深蓝 → 青 → 黄 → 红
    sdrsharp: ramp([[0, [0, 0, 0]], [0.2, [0, 0, 140]], [0.45, [0, 160, 255]], [0.65, [0, 255, 120]],
      [0.8, [255, 255, 0]], [0.92, [255, 90, 0]], [1, [255, 0, 0]]]),
    turbo: ramp([[0, [48, 18, 59]], [0.15, [70, 107, 227]], [0.3, [40, 187, 236]], [0.45, [50, 241, 152]],
      [0.6, [164, 252, 60]], [0.75, [251, 185, 56]], [0.9, [228, 76, 13]], [1, [122, 4, 3]]]),
    viridis: ramp([[0, [68, 1, 84]], [0.25, [59, 82, 139]], [0.5, [33, 145, 140]], [0.75, [94, 201, 98]], [1, [253, 231, 37]]]),
    gray: ramp([[0, [0, 0, 0]], [1, [255, 255, 255]]]),
  };
})();
